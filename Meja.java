public class Meja {
    private int nomorMeja;
    private int kapasitas;

    public Meja(int nomorMeja, int kapasitas) {
        this.nomorMeja = nomorMeja;
        this.kapasitas = kapasitas;
    }

    public int getNomorMeja() {
        return nomorMeja;
    }

    public int getKapasitas() {
        return kapasitas;
    }
}